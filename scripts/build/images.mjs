// `npm run images`: builds AVIF + WebP + fallback (JPG for scenes, PNG for cutouts) in several widths
// into public/images/ and writes src/data/images.generated.js with exact sizes (no layout shift).
import sharp from 'sharp';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';
import { specs } from './images.config.mjs';

const OUT = 'public/images';
mkdirSync(OUT, { recursive: true });
const meta = {};

for (const spec of specs) {
  if (!existsSync(spec.src)) {
    console.warn(`skip ${spec.name}: master not found (${spec.src})`);
    continue;
  }
  let base = sharp(spec.src);
  if (spec.crop) base = base.extract(spec.crop);
  const buf = await base.toBuffer();
  const { width: mw, height: mh } = await sharp(buf).metadata();
  mkdirSync(dirname(`${OUT}/${spec.name}`), { recursive: true });
  const entry = { width: mw, height: mh, kind: spec.kind, variants: [] };
  if (spec.box) {
    // convert master-relative fractions into fractions of this output (crop)
    const c = spec.crop ?? { left: 0, top: 0, width: 2752, height: 1536 };
    const X = (f) => (f * 2752 - c.left) / c.width;
    const Y = (f) => (f * 1536 - c.top) / c.height;
    const r = (n) => Math.round(n * 1000) / 1000;
    entry.box = {
      x: r(X(spec.box.l)),
      y: r(Y(spec.box.t)),
      w: r(X(spec.box.r) - X(spec.box.l)),
      h: r(Y(spec.box.b) - Y(spec.box.t)),
    };
    entry.focal = { x: r(X(spec.focal.x)), y: r(Y(spec.focal.y)) };
  }
  for (const w of spec.widths) {
    const width = Math.min(w, mw); // never upscale
    const height = Math.round((mh * width) / mw);
    const img = () => sharp(buf).resize({ width, kernel: 'lanczos3' });
    await img()
      .avif({ quality: spec.kind === 'scene' ? 48 : 55, effort: 5 })
      .toFile(`${OUT}/${spec.name}-${width}.avif`);
    await img().webp({ quality: 80 }).toFile(`${OUT}/${spec.name}-${width}.webp`);
    if (spec.kind === 'scene')
      await img().jpeg({ quality: 80, mozjpeg: true }).toFile(`${OUT}/${spec.name}-${width}.jpg`);
    else
      await img()
        .png({ compressionLevel: 9, palette: true, quality: 85, effort: 8 })
        .toFile(`${OUT}/${spec.name}-${width}.png`);
    if (!entry.variants.some((v) => v.width === width)) entry.variants.push({ width, height });
  }
  meta[spec.name] = entry;
  console.log(`${spec.name}: ${mw}x${mh} → ${entry.variants.map((v) => v.width).join('/')}`);
}

writeFileSync(
  'src/data/images.generated.js',
  `// GENERATED by scripts/build/images.mjs — do not edit.\nexport const images = ${JSON.stringify(meta, null, 2)};\n`,
);

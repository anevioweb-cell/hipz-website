// `npm run copy:review` → docs/content/COPY_REVIEW.md: every copy entry from src/data/copy.js grouped by page and
// section (key, English text, Arabic accents, status, character count), a list of everything still
// draft: true, and the banned-claims scan over copy.js + story.js. For the owner to review before the
// site is shown to Kada and Miloud. Regenerate after every copy change.
import { writeFileSync } from 'node:fs';
import { copy } from '../../src/data/copy.js';
import { story } from '../../src/data/story.js';
import {
  BANNED,
  DIGIT_ALLOW,
  allowedDigits,
  checkString,
  collectStrings,
} from '../../src/data/bannedClaims.js';

const PAGES = [
  ['Every page (navigation, footer, titles and link previews)', ['meta', 'nav', 'footer']],
  ['Home (/)', ['hero', 'ticker', 'sections', 'moments', 'why', 'both', 'community']],
  ['Flavors (/flavors and /flavors/:slug)', ['flavors']],
  ['Distributors (/distributors)', ['distributors']],
  ['Our story (/our-story)', ['story']],
];

// leaves = objects carrying `draft`
const leaves = [];
(function walk(node, path) {
  if (node && typeof node === 'object' && !Array.isArray(node) && 'draft' in node)
    leaves.push([path, node]);
  else if (node && typeof node === 'object')
    for (const [k, v] of Object.entries(node)) walk(v, path ? `${path}.${k}` : k);
})(copy, '');

const isArabicKey = (k) => k === 'ar' || /Ar$/.test(k);
const flat = (v) =>
  Array.isArray(v)
    ? v
        .map((x) =>
          typeof x === 'object'
            ? Object.values(x)
                .filter((y) => typeof y === 'string')
                .join(' — ')
            : x,
        )
        .join(' / ')
    : String(v);
const esc = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function rows(path, leaf) {
  const out = [];
  for (const [k, v] of Object.entries(leaf)) {
    if (k === 'draft' || isArabicKey(k)) continue;
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      // nested group (e.g. form errors): one row per string
      for (const [k2, v2] of Object.entries(v))
        if (typeof v2 === 'string' || Array.isArray(v2)) out.push([`${path}.${k}.${k2}`, flat(v2)]);
      continue;
    }
    if (typeof v === 'string' || Array.isArray(v)) out.push([`${path}.${k}`, flat(v)]);
  }
  const ar = Object.entries(leaf)
    .filter(([k]) => isArabicKey(k))
    .map(([, v]) => v)
    .join(' · ');
  return { out, ar };
}

let md = `# Copy review

Generated by \`npm run copy:review\` from \`src/data/copy.js\` on ${new Date().toISOString().slice(0, 10)}. **Do not edit by hand** — change \`copy.js\` and regenerate.

Status: **approved** = owner-approved (\`draft: false\`), **draft** = waiting for the owner. Character counts are for the English text. Arabic accent words render through \`<Ar>\` (right-to-left, Arabic font).

`;
let total = 0;
let drafts = 0;
const draftList = [];
for (const [page, keys] of PAGES) {
  md += `## ${page}\n\n`;
  for (const top of keys) {
    const group = leaves.filter(([p]) => p === top || p.startsWith(`${top}.`));
    const sections = new Map();
    for (const [p, leaf] of group) {
      const sec = p.split('.').slice(0, 2).join('.');
      if (!sections.has(sec)) sections.set(sec, []);
      sections.get(sec).push([p, leaf]);
    }
    for (const [sec, items] of sections) {
      md += `### \`${sec}\`\n\n| Key | English | Arabic accents | Status | Chars |\n|---|---|---|---|---|\n`;
      for (const [p, leaf] of items) {
        const { out, ar } = rows(p, leaf);
        total++;
        if (leaf.draft) {
          drafts++;
          draftList.push(p);
        }
        out.forEach(([key, text], i) => {
          md += `| \`${key}\` | ${esc(text)} | ${i === 0 && ar ? esc(ar) : ''} | ${leaf.draft ? 'draft' : '**approved**'} | ${text.length} |\n`;
        });
        if (!out.length)
          md += `| \`${p}\` | — | ${esc(ar)} | ${leaf.draft ? 'draft' : '**approved**'} | 0 |\n`;
      }
      md += '\n';
    }
  }
}

md += `## Still draft (${drafts} of ${total} entries)\n\nEverything below needs the owner's approval before the site is shown to Kada and Miloud:\n\n`;
md += draftList.map((p) => `- \`${p}\``).join('\n') + '\n\n';

// banned-claims scan
const strings = [...collectStrings(copy, 'copy'), ...collectStrings(story, 'story')];
const flagged = strings.map(([p, s]) => [p, s, checkString(s)]).filter(([, , f]) => f.length);
const allowedHits = strings.map(([p, s]) => [p, s, allowedDigits(s)]).filter(([, , a]) => a.length);
md += `## Banned-claims scan (copy.js + story.js, ${strings.length} strings)\n\n`;
md += `Rules (\`src/data/bannedClaims.js\`, easy to extend): ${BANNED.map((b) => `${b.why}`).join('; ')}; and any digit except the allow-list.\n\n`;
md += flagged.length
  ? `**Flagged (${flagged.length}):**\n\n${flagged.map(([p, s, f]) => `- \`${p}\`: “${esc(s)}” — ${f.map((x) => x.why).join(', ')}`).join('\n')}\n\n`
  : '**Flagged: none.**\n\n';
md += `Digits that are allowed, and why:\n\n${allowedHits.map(([p, s, a]) => `- \`${p}\`: “${esc(s)}” — ${a.map((x) => x.why).join('; ')}`).join('\n')}\n\n`;
md += `Allow-list: ${DIGIT_ALLOW.map((a) => `\`${a.pattern}\` (${a.why})`).join('; ')}.\n`;

writeFileSync('docs/content/COPY_REVIEW.md', md);
console.log(
  `docs/content/COPY_REVIEW.md: ${total} entries, ${drafts} draft, ${strings.length} strings scanned, ${flagged.length} flagged`,
);

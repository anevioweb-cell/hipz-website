// Writes docs/QA_MATRIX.md from docs/qa-matrix.json (scripts/qa-matrix.mjs) and docs/qa-devices.json
// (scripts/qa-devices.mjs). Usage: node scripts/qa-report.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const m = JSON.parse(readFileSync('docs/qa-matrix.json', 'utf8'));
const d = JSON.parse(readFileSync('docs/qa-devices.json', 'utf8'));
const ROUTES = [...new Set(m.pages.map((p) => p.path))];
const ENGINES = Object.keys(m.versions);
const WIDTHS = [...new Set(m.pages.map((p) => p.width))];

const verdict = (p) => {
  const notes = [];
  if (p.errors.length) notes.push(`${p.errors.length} console error(s)`);
  if (p.failed.length) notes.push(`${p.failed.length} failed request(s)`);
  if (p.overflowX > 0) notes.push(`overflow ${p.overflowX}px`);
  if (p.hidden.length) notes.push(`${p.hidden.length} hidden`);
  if (p.cornerOk === false) notes.push('square corner');
  if (p.shell === 'STILL VISIBLE') notes.push('pre-JS frame not handed over');
  return notes.length ? `FAIL: ${notes.join(', ')}` : 'pass';
};

let md = `# QA matrix

Generated by \`node scripts/qa-report.mjs\` from \`scripts/qa-matrix.mjs\` (${m.at.slice(0, 10)}) and \`scripts/qa-devices.mjs\` (${d.at.slice(0, 10)}), against a production build served locally (${m.base}). Screenshots: \`docs/shots/qa/\` (gitignored).

Engines (Playwright builds): ${ENGINES.map((e) => `${e} ${m.versions[e]}`).join(', ')}. **WebKit is the closest engine to Safari available on Linux, not Safari itself**; no real iPhone, Android phone or iPad was tested.

Each cell checks: no console errors or failed requests, no horizontal overflow, nothing left at opacity 0 / scale 0 after a full scroll, rounded hero corners during the hero animation (corner pixel = page background), the static pre-JS first frame handed over (hidden) after load. The image format each engine chose through \`<picture>\` is in brackets.

`;
for (const engine of ENGINES) {
  md += `## ${engine}\n\n| Route | ${WIDTHS.map((w) => `${w}`).join(' | ')} |\n|---|${WIDTHS.map(() => '---').join('|')}|\n`;
  for (const r of ROUTES) {
    const cells = WIDTHS.map((w) => {
      const p = m.pages.find((x) => x.engine === engine && x.path === r && x.width === w);
      return p ? `${verdict(p)}${p.format ? ` (${p.format})` : ''}` : '—';
    });
    md += `| \`${r}\` | ${cells.join(' | ')} |\n`;
  }
  md += '\n';
}

md += `## Keyboard tour (1440, Tab / Option+Tab in WebKit)\n\n| Engine | Route | Stops | Invisible when focused | No visible focus ring |\n|---|---|---|---|---|\n`;
for (const k of m.keyboard)
  md += `| ${k.engine} | \`${k.path}\` | ${k.stops} | ${k.invisible.length ? k.invisible.join(', ') : 'none'} | ${k.noRing.length ? k.noRing.join(', ') : 'none'} |\n`;

md += `\n## Reduced motion (390, prefers-reduced-motion: reduce)\n\n| Engine | Route | Split text pieces | Animated blocks | Invisible text |\n|---|---|---|---|---|\n`;
for (const r of m.reduced)
  md += `| ${r.engine} | \`${r.path}\` | ${r.split} | ${r.animatedBlocks} | ${r.invisibleText} |\n`;

md += `\n## Devices (Playwright device profiles — emulation, not real hardware)\n\n| Device | Engine | Viewport / DPR | Overflow (all routes) | Carousel swipe | Mobile menu | Rotation |\n|---|---|---|---|---|---|---|\n`;
for (const x of d.devices) {
  const ov = Object.values(x.overflow).every((v) => v <= 0) ? 'none' : JSON.stringify(x.overflow);
  const car =
    typeof x.carousel === 'string'
      ? x.carousel
      : `moved ${x.carousel.moved}px, ${x.carousel.snapped ? 'snapped' : 'NOT snapped'}`;
  const menu =
    typeof x.menu === 'string'
      ? x.menu
      : `focus ${x.menu.trapped ? 'trapped' : 'ESCAPES'}, Esc ${x.menu.closedOnEscape ? 'closes' : 'does NOT close'}, focus ${x.menu.focusBack ? 'returns' : 'lost'}`;
  const rot = x.rotated
    ? `overflow ${x.rotated.overflow}px, frame ${x.rotated.frameH}px in ${x.rotated.vh}px`
    : '—';
  md += `| ${x.device} | ${x.engine} | ${x.viewport.width}×${x.viewport.height} @${x.dpr}x | ${ov} | ${car} | ${menu} | ${rot} |\n`;
}
md += `\nReflow: ${d.reflow.map((r) => `${r.label}: ${Object.values(r.overflow).every((v) => v <= 0) ? 'no horizontal overflow on any route' : JSON.stringify(r.overflow)}`).join('; ')}.\n`;
md += `\nSafe areas: \`viewport-fit=cover\` is set; the body pads \`env(safe-area-inset-left/right)\`, the navbar and the mobile menu respect all insets, the footer pads \`env(safe-area-inset-bottom)\`. Emulation reports all insets as 0, so the notch behaviour itself is unverified without a real iPhone.\n`;
writeFileSync('docs/QA_MATRIX.md', md);
console.log('docs/QA_MATRIX.md written');

// `npm run notices` → THIRD_PARTY_NOTICES.md: every package that ships in the built site (the production
// dependency tree, read from node_modules) with version and license, plus the font licenses.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { encoding: 'utf8' }));
const seen = new Map();
(function walk(deps = {}) {
  for (const [name, d] of Object.entries(deps)) {
    if (!d.version) continue; // optional peer dependency that is not installed (not shipped)
    if (!seen.has(name)) {
      let license = 'see package';
      let repo = '';
      try {
        const pj = JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8'));
        license = typeof pj.license === 'string' ? pj.license : pj.license?.type || license;
        repo =
          typeof pj.repository === 'string'
            ? pj.repository
            : pj.repository?.url || pj.homepage || '';
      } catch {
        // not hoisted: keep defaults
      }
      seen.set(name, {
        version: d.version,
        license,
        repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''),
      });
    }
    walk(d.dependencies);
  }
})(tree.dependencies);
const direct = new Set(Object.keys(JSON.parse(readFileSync('package.json', 'utf8')).dependencies));
const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const md = `# Third-party notices

Generated by \`npm run notices\` from the production dependency tree (packages that end up in the built site). Development tools (Vite, ESLint, Playwright, Vitest, sharp, …) are not shipped and are not listed.

| Package | Version | License | Direct | Source |
|---|---|---|---|---|
${rows.map(([n, d]) => `| \`${n}\` | ${d.version} | ${d.license} | ${direct.has(n) ? 'yes' : ''} | ${d.repo} |`).join('\n')}

## Fonts

All fonts are self-hosted from \`@fontsource\` packages and licensed under the **SIL Open Font License 1.1** (Bricolage Grotesque, Inter, DM Mono, Cairo, Baloo Bhaijaan 2). Details, versions and sources: \`docs/brand/FONT_LICENSES.md\`.

## Images and brand assets

Not third-party open-source material: the Hipz logo and bottle photos are the brand owner's; the hero and flavor scenes are AI-generated concept art made by the owner from real bottle photos; creator photos come from Kada & Miloud's own public accounts and need their written permission before any public use (\`docs/content/CREATOR_PHOTOS.md\`).
`;
writeFileSync('THIRD_PARTY_NOTICES.md', md);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} runtime packages`);
